#!/usr/bin/env bash
# Builds SDL3_mixer for web exports: libSDL3_mixer.a, compiled with Emscripten from the
# third_party/SDL_mixer submodule (Emscripten has no SDL3_mixer port). Run by `task emsdk`.
#
# Usage: tools/build_web_mixer.sh <emsdk folder> <SDL_mixer folder> <output folder>
#
# Decoders: the ones SDL_mixer carries itself (WAV, AIFF, AU, VOC, FLAC via dr_flac, MP3 via
# dr_mp3, OGG Vorbis via stb_vorbis); no external libraries.
#
# Odin's vendor:sdl3/mixer binding has no wasm branch: on js_wasm32 it imports its functions from
# the module "system:SDL3_mixer", so the object Odin writes asks for symbols named
# "system:SDL3_mixer..MIX_Init" and so on. A wrapper file includes SDL_mixer.c (where every public
# function is defined) and gives each function an alias under that name, so the game links
# against this library directly.
set -euo pipefail

emsdk=$1
mixer=$2
out=$3
emcc="$emsdk/upstream/emscripten/emcc"
emar="$emsdk/upstream/emscripten/emar"

mkdir -p "$out/obj"
flags=(-I"$mixer/include" -I"$mixer/src" -sUSE_SDL=3 -O2
	-DDECODER_WAV -DDECODER_AIFF -DDECODER_AU -DDECODER_VOC
	-DDECODER_FLAC_DRFLAC -DDECODER_MP3_DRMP3 -DDECODER_OGGVORBIS_STB)

# SDL_mixer.c plus the aliases Odin's object links against
wrapper="$out/obj/SDL_mixer_odin.c"
{
	echo "// Generated by tools/build_web_mixer.sh: SDL_mixer.c, with each public function also"
	echo "// under the name Odin's js_wasm32 binding imports it by."
	echo "#include \"SDL_mixer.c\""
	for name in $(grep -o 'MIX_[A-Za-z0-9_]*' "$mixer/src/SDL_mixer.sym"); do
		echo "extern __typeof__($name) odin_alias_$name __asm__(\"system:SDL3_mixer..$name\") __attribute__((alias(\"$name\")));"
	done
} > "$wrapper"
"$emcc" -c "$wrapper" -o "$out/obj/SDL_mixer.o" "${flags[@]}"

for source in SDL_mixer_metadata_tags SDL_mixer_spatialization decoder_wav decoder_aiff decoder_au \
	decoder_voc decoder_raw decoder_sinewave decoder_drflac decoder_drmp3 decoder_stb_vorbis; do
	"$emcc" -c "$mixer/src/$source.c" -o "$out/obj/$source.o" "${flags[@]}"
done

rm -f "$out/libSDL3_mixer.a"
"$emar" rcs "$out/libSDL3_mixer.a" "$out"/obj/*.o
echo "Built $out/libSDL3_mixer.a"
